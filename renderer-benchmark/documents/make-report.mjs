// Write documents/report.html: a long report with tables (30 A4 pages in Chrome).
// The data comes from a seeded random generator, so every run writes the same file.
// Usage: node documents/make-report.mjs
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const SECTIONS = 10;
const ROWS_PER_SECTION = 88;

const CUSTOMERS = ['Harbor & Pine Studio', 'Northgate Clinics', 'Blue Fern Retail', 'Atlas Freight', 'Mosaic Learning',
  'Oakline Insurance', 'Sundial Travel', 'Granite Legal', 'Brightwater Utilities', 'Copperleaf Foods'];
const COUNTRIES = ['United Kingdom', 'Germany', 'France', 'Netherlands', 'Spain', 'Ireland', 'Poland', 'Sweden'];
const STATUSES = ['Paid', 'Paid', 'Paid', 'Open', 'Overdue'];
const REGIONS = ['North', 'South', 'East', 'West', 'Central', 'Coast'];

// A small seeded random number generator (mulberry32).
function random(seed) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const escape = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const money = (cents) => (cents / 100).toLocaleString('en-GB', { minimumFractionDigits: 2 });

export function reportHtml() {
  const next = random(2026);
  const pick = (list) => list[Math.floor(next() * list.length)];
  const sections = [];
  let order = 41000;

  for (let s = 1; s <= SECTIONS; s++) {
    const rows = [];
    let total = 0;
    for (let r = 0; r < ROWS_PER_SECTION; r++) {
      const cents = Math.floor(next() * 900000) + 2500;
      total += cents;
      const day = String(1 + Math.floor(next() * 28)).padStart(2, '0');
      rows.push(
        `<tr><td>2026-${String(((s - 1) % 12) + 1).padStart(2, '0')}-${day}</td><td>SO-${order++}</td>` +
          `<td>${escape(pick(CUSTOMERS))}</td><td>${pick(COUNTRIES)}</td>` +
          `<td class="num">${1 + Math.floor(next() * 40)}</td><td class="num">${money(cents)}</td>` +
          `<td>${pick(STATUSES)}</td></tr>`,
      );
    }
    sections.push(`<section>
  <h2>${s}. ${pick(REGIONS)} region, month ${s}</h2>
  <p>This section lists the ${ROWS_PER_SECTION} orders of month ${s}. Amounts are in euros and include VAT.
  The status column shows the payment state on the last day of the month.</p>
  <table>
    <thead><tr><th>Date</th><th>Order</th><th>Customer</th><th>Country</th><th class="num">Items</th><th class="num">Amount</th><th>Status</th></tr></thead>
    <tbody>
${rows.join('\n')}
    </tbody>
    <tfoot><tr><td colspan="5">Total for month ${s}</td><td class="num">${money(total)}</td><td></td></tr></tfoot>
  </table>
</section>`);
  }

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>Order report 2026</title>
  <style>
    /* Benchmark document 2: a long report with tables. Generated by make-report.mjs. */
    @page { size: A4; margin: 16mm 15mm; }
    html { font: 9pt/1.4 "Liberation Sans", Arial, Helvetica, sans-serif; color: #1f2933; }
    body { margin: 0; }
    h1 { font-size: 22pt; margin: 0 0 6px; color: #0f766e; }
    h2 { font-size: 13pt; margin: 18px 0 6px; break-after: avoid; }
    p { margin: 0 0 8px; }
    table { width: 100%; border-collapse: collapse; }
    th { background: #e6f4f1; text-align: left; padding: 4px 6px; border-bottom: 1px solid #0f766e; }
    td { padding: 3px 6px; border-bottom: 1px solid #e4e7eb; }
    tr { break-inside: avoid; }
    tfoot td { font-weight: bold; border-top: 1px solid #1f2933; }
    tfoot { display: table-row-group; }
    .num { text-align: right; }
    section { break-before: page; }
    section:first-of-type { break-before: auto; }
  </style>
</head>
<body>
  <h1>Order report 2026</h1>
  <p>${SECTIONS} months, ${SECTIONS * ROWS_PER_SECTION} orders. Each month starts on a new page.</p>
${sections.join('\n')}
</body>
</html>
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = new URL('./report.html', import.meta.url);
  writeFileSync(file, reportHtml());
  console.log(`Wrote ${file.pathname}`);
}
